function eza(slug, p) {
  // Quoted: in YAML a # after a space starts a comment, and an unquoted colour would silently be null.
  const style = ([name, ...flags]) => `{${[`foreground: "${slot(p, name)}"`, ...flags.map((f) => `is_${f}: true`)].join(', ')}}`
  const pick = (path, value) => EZA_OVERRIDES[slug][path] ?? value
  const lines = [
    header(slug, p, 'theme for eza (https://eza.rocks)', '#', [
      'Use: save as theme.yml in a folder and set EZA_CONFIG_DIR to it, or put it in eza\'s default folder',
      '(~/.config/eza on Linux, ~/Library/Application Support/eza on macOS). LS_COLORS and EZA_COLORS override it.',
    ]),
  ]
  for (const [key, value] of Object.entries(EZA)) {
    if (Array.isArray(value)) {
      lines.push(`${key}: ${style(pick(key, value))}`)
      continue
    }
    lines.push(`${key}:`)
    for (const [sub, v] of Object.entries(value)) lines.push(`  ${sub}: ${style(pick(`${key}.${sub}`, v))}`)
  }
  return `${lines.join('\n')}\n`
}

// ---------------------------------------------------------------- status line palettes

/** The status line script with its palettes block rewritten from `palettes`. */
export function withPalettes(source, palettes) {
  const start = source.indexOf(BEGIN)
  const end = source.indexOf(END)
  if (start < 0 || end < start) throw new Error(`${STATUSLINE}: no ${BEGIN} ... ${END} block`)
  const body = JSON.stringify(palettes, null, 2).replace(/\[\s+("#[^\]]+?)\s+\]/g, (_, list) => `[${list.split(/,\s+/).join(', ')}]`)
  const line = source.slice(start, source.indexOf('\n', start))
  return `${source.slice(0, start)}${line}\nexport const PALETTES = ${body}\n${source.slice(end)}`
}

/** Every extras file as { relative path: content }, from the theme files under `root`. */
export function buildExtras(root = ROOT) {
  const palettes = loadPalettes(root)
  const files = {}
  for (const slug of SLUGS) {
    const p = palettes[slug]
    files[`extras/${slug}/starship.toml`] = starship(slug, p, STARSHIP[slug](p))
    files[`extras/${slug}/bat.tmTheme`] = tmTheme(slug, p)
    files[`extras/${slug}/delta.gitconfig`] = delta(slug, p)
    files[`extras/${slug}/eza.yml`] = eza(slug, p)
  }
  files[STATUSLINE] = withPalettes(readFileSync(join(root, STATUSLINE), 'utf8'), palettes)
  return files
}

/** The files under `root` that differ from what buildExtras makes. */
export function staleExtras(root = ROOT) {
  return Object.entries(buildExtras(root)).filter(([file, body]) => {
    try {
      return readFileSync(join(root, file), 'utf8') !== body
    } catch {
      return true
    }
  }).map(([file]) => file)
}

const real = (p) => {
  try {
    return realpathSync(p)
  } catch {
    return resolve(p)
  }
}
if (process.argv[1] && real(process.argv[1]) === real(fileURLToPath(import.meta.url))) {
  if (process.argv.includes('--check')) {
    const stale = staleExtras()
    for (const file of stale) console.error(`${file}: out of date, run node extras/make-extras.mjs`)
    if (stale.length) process.exit(1)
    console.log('ok: extras up to date')
  } else {
    const stale = new Set(staleExtras())
    for (const [file, body] of Object.entries(buildExtras())) {
      if (!stale.has(file)) continue
      mkdirSync(dirname(join(ROOT, file)), { recursive: true })
      writeFileSync(join(ROOT, file), body)
      console.log(`wrote ${file}`)
    }
    if (!stale.size) console.log('ok: extras up to date')
  }
}
