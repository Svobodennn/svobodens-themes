function delta(slug, p) {
  const red = p.ansi[1]
  const green = p.ansi[2]
  // In git config a # outside quotes starts a comment, so every colour is quoted.
  const q = (hex) => `"${hex}"`
  const rows = {
    dark: 'true',
    'syntax-theme': `svoboden-${slug}`,
    'minus-style': `syntax ${q(mix(red, p.bg, 0.2))}`,
    'minus-emph-style': `syntax ${q(mix(red, p.bg, 0.42))}`,
    'plus-style': `syntax ${q(mix(green, p.bg, 0.18))}`,
    'plus-emph-style': `syntax ${q(mix(green, p.bg, 0.38))}`,
    'zero-style': 'syntax',
    'whitespace-error-style': `${q(red)} reverse`,
    'file-style': `${q(p.accent)} bold`,
    'file-decoration-style': `${q(p.accent)} ul`,
    'hunk-header-style': 'file line-number syntax',
    'hunk-header-decoration-style': `${q(p.ansi[8])} box`,
    'hunk-header-file-style': q(p.ansi[6]),
    'hunk-header-line-number-style': q(p.accent),
    'commit-decoration-style': `${q(p.accent)} box ul`,
    'line-numbers-minus-style': q(red),
    'line-numbers-plus-style': q(green),
    'line-numbers-zero-style': q(p.ansi[8]),
    'line-numbers-left-style': q(p.selection),
    'line-numbers-right-style': q(p.selection),
  }
  return [
    header(slug, p, 'colours for delta (https://github.com/dandavison/delta)', '#', [
      'Use, in ~/.gitconfig:',
      '  [include]',
      `      path = /path/to/extras/${slug}/delta.gitconfig`,
      '  [delta]',
      `      features = ${slug}`,
      `syntax-theme is the bat theme from bat.tmTheme, installed as svoboden-${slug} (delta reads bat's cache).`,
    ]),
    `[delta "${slug}"]`,
    ...Object.entries(rows).map(([k, v]) => `    ${k} = ${v}`),
    '',
  ].join('\n')
}

