// ---------------------------------------------------------------- Starship

const toml = (s) => `'${s}'` // literal string: Starship's own escapes (\[, \$) pass through as written

const ASCII_GIT_STATUS = {
  ahead: '^${count}', behind: 'v${count}', diverged: '^${ahead_count}v${behind_count}', conflicted: '=',
  deleted: 'x', renamed: 'r', modified: '!', staged: '+', untracked: '?', stashed: '\\$',
}

const table = (name, values) => [`[${name}]`, ...Object.entries(values).map(([k, v]) =>
  `${k} = ${typeof v === 'string' ? toml(v) : v}`)].join('\n')

function starship(slug, p, design) {
  const name = `svoboden_${slug.replaceAll('-', '_')}`
  return [
    header(slug, p, 'prompt for Starship (https://starship.rs)', '#', [
      `Use: STARSHIP_CONFIG=/path/to/extras/${slug}/starship.toml, or copy it to ~/.config/starship.toml.`,
    ]),
    `"$schema" = 'https://starship.rs/config-schema.json'`,
    '',
    `palette = ${toml(name)}`,
    'add_newline = true',
    `continuation_prompt = ${toml(design.continuation)}`,
    `format = ${toml(design.format)}`,
    '',
    table(`palettes.${name}`, design.palette),
    '',
    table('directory', { truncation_length: 3, truncation_symbol: '../', home_symbol: '~', read_only: ' RO', ...design.directory }),
    '',
    table('git_branch', { symbol: '', truncation_symbol: '..', ...design.git_branch }),
    '',
    table('git_status', { ...ASCII_GIT_STATUS, ...design.git_status }),
    '',
    table('cmd_duration', { min_time: 2000, ...design.cmd_duration }),
    '',
    table('line_break', { disabled: false }),
    '',
    table('character', design.character),
    '',
  ].join('\n')
}

