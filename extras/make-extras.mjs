#!/usr/bin/env node
// The terminal extras, built from the theme palettes in themes/<slug>.json so the colours have one source: a Starship
// prompt, a bat theme, a delta feature and an eza theme per theme, and the palettes inside the status line script.
// Node, no dependencies. Run: node extras/make-extras.mjs   (--check: list stale files and write nothing)
//
// Width: the terminals these are for run GNU screen 4.00.03, where an emoji or a variation selector shifts the rest
// of the row. So every symbol here is ASCII, box drawing or one of the two single-code-point marks the prompts ask
// for (U+258B, U+25B8), and every Starship default that isn't (the lock, the branch glyph, the arrows) is replaced.
import { mkdirSync, readFileSync, realpathSync, writeFileSync } from 'node:fs'
