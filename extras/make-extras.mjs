/** Each theme's colours as the app has them: { name, bg, fg, cursor, selection, accent, ansi[16] }. */
export function loadPalettes(root = ROOT) {
  return Object.fromEntries(SLUGS.map((slug) => {
    const t = JSON.parse(readFileSync(join(root, 'themes', `${slug}.json`), 'utf8'))
    return [slug, { name: t.name, bg: t.bg, fg: t.fg, cursor: t.cursor, selection: t.selection, accent: t.accent, ansi: t.ansi }]
  }))
}

/** a over b at `t` (0 = b, 1 = a), as #rrggbb. */
export function mix(a, b, t) {
  const ch = (hex, i) => parseInt(hex.slice(1 + 2 * i, 3 + 2 * i), 16)
  return `#${[0, 1, 2].map((i) => Math.round(ch(a, i) * t + ch(b, i) * (1 - t)).toString(16).padStart(2, '0')).join('')}`
}

/** A palette slot ('bg', 'accent', 'ansi6'…) to its colour. */
const slot = (p, name) => {
  const value = name.startsWith('ansi') ? p.ansi[Number(name.slice(4))] : p[name]
  if (!/^#[0-9a-f]{6}$/i.test(value ?? '')) throw new Error(`no colour "${name}"`)
  return value
}

