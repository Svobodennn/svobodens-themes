// ---------------------------------------------------------------- bat (TextMate theme)

const xml = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')

// An XML comment may not hold "--", so the install steps (bat --theme ...) live in the README.
const xmlComment = (slug, p) => {
  const text = `Svoboden's Themes: ${p.name} theme for bat. Generated by extras/make-extras.mjs from themes/${slug}.json;`
    + ' change those, not this file. To install it, see "Terminal extras" in the README.'
  if (text.includes('--')) throw new Error('"--" in an XML comment')
  return text
}

function tmTheme(slug, p) {
  const r = Object.fromEntries(Object.entries(SYNTAX[slug]).map(([role, name]) => [role, slot(p, name)]))
  const rules = [
    ['Comment', 'comment, punctuation.definition.comment', { foreground: r.comment, fontStyle: 'italic' }],
    ['String', 'string, punctuation.definition.string', { foreground: r.string }],
    ['Number', 'constant.numeric', { foreground: r.number }],
    ['Built-in constant', 'constant.language, support.constant, variable.other.constant', { foreground: r.constant }],
    ['Escape', 'constant.character.escape, constant.other.placeholder, string.regexp', { foreground: r.escape }],
    ['Keyword', 'keyword, keyword.control', { foreground: r.keyword }],
    ['Operator', 'keyword.operator, punctuation.separator, punctuation.accessor', { foreground: r.operator }],
    ['Storage', 'storage, storage.type, storage.modifier', { foreground: r.storage }],
    ['Function', 'entity.name.function, support.function, variable.function', { foreground: r.function }],
    ['Type', 'entity.name.type, entity.name.class, entity.other.inherited-class, support.type, support.class', { foreground: r.type }],
    ['Variable', 'variable, variable.other', { foreground: p.fg }],
    ['Parameter', 'variable.parameter', { foreground: r.parameter, fontStyle: 'italic' }],
    ['Language variable', 'variable.language', { foreground: r.storage, fontStyle: 'italic' }],
    ['Tag', 'entity.name.tag', { foreground: r.tag }],
    ['Attribute', 'entity.other.attribute-name', { foreground: r.attribute }],
    ['Heading', 'markup.heading, entity.name.section', { foreground: r.heading, fontStyle: 'bold' }],
    ['Bold', 'markup.bold', { fontStyle: 'bold' }],
    ['Italic', 'markup.italic', { fontStyle: 'italic' }],
    ['Link', 'markup.underline.link, string.other.link', { foreground: r.link, fontStyle: 'underline' }],
    ['Inline code', 'markup.raw, markup.inline.raw', { foreground: r.string }],
    ['Quote', 'markup.quote', { foreground: r.comment, fontStyle: 'italic' }],
    ['Inserted', 'markup.inserted', { foreground: r.inserted }],
    ['Deleted', 'markup.deleted', { foreground: r.deleted }],
    ['Changed', 'markup.changed', { foreground: r.changed }],
    ['Diff header', 'meta.diff.header, meta.diff.range, meta.diff.index', { foreground: r.heading }],
    ['Invalid', 'invalid, invalid.illegal', { foreground: p.bg, background: r.deleted }],
  ]
  const dict = (pad, values) => [
    `${pad}<dict>`,
    ...Object.entries(values).flatMap(([k, v]) => [`${pad}\t<key>${xml(k)}</key>`, `${pad}\t<string>${xml(v)}</string>`]),
    `${pad}</dict>`,
  ]
  const globals = {
    background: p.bg, foreground: p.fg, caret: p.cursor, selection: p.selection,
    lineHighlight: mix(p.fg, p.bg, 0.07), invisibles: p.ansi[8], gutterForeground: p.ansi[8],
  }
  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">',
    `<!-- ${xmlComment(slug, p)} -->`,
    '<plist version="1.0">',
    '<dict>',
    '\t<key>name</key>',
    `\t<string>${xml(`Svoboden ${p.name}`)}</string>`,
    '\t<key>settings</key>',
    '\t<array>',
    '\t\t<dict>',
    '\t\t\t<key>settings</key>',
    ...dict('\t\t\t', globals),
    '\t\t</dict>',
    ...rules.flatMap(([name, scope, settings]) => [
      '\t\t<dict>',
      '\t\t\t<key>name</key>',
      `\t\t\t<string>${xml(name)}</string>`,
      '\t\t\t<key>scope</key>',
      `\t\t\t<string>${xml(scope)}</string>`,
      '\t\t\t<key>settings</key>',
      ...dict('\t\t\t', settings),
      '\t\t</dict>',
    ]),
    '\t</array>',
    '</dict>',
    '</plist>',
    '',
  ].join('\n')
}

